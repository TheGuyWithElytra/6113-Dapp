import { chromium } from '@playwright/test';
import ganache from 'ganache';
import assert from 'node:assert/strict';
import { preview } from 'vite';
const server=await preview({preview:{host:'127.0.0.1',port:4174,strictPort:true}});
const rpc=ganache.provider({chain:{chainId:11155111},logging:{quiet:true}});
await rpc.request({method:'eth_accounts',params:[]});let browser;
try{
  browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.exposeFunction('walletRpc',async payload=>rpc.request(payload.method==='eth_requestAccounts'?{...payload,method:'eth_accounts'}:payload));
  await page.addInitScript(()=>{window.walletListeners={};window.ethereum={request:payload=>window.walletRpc(payload),on:(event,fn)=>{window.walletListeners[event]=fn;}};});
  await page.goto('http://127.0.0.1:4174');
  await page.locator('#file').setInputFiles({name:'proof.txt',mimeType:'text/plain',buffer:Buffer.from('abc')});
  await page.getByText('Fingerprint computed. File contents and filename were not uploaded.',{exact:true}).waitFor();
  assert.equal(await page.locator('#fingerprint').inputValue(),'0xba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
  await page.locator('#connect').click();await page.getByText('Wallet connected. Load or deploy a registry contract.',{exact:true}).waitFor();
  await page.locator('summary').click();await page.locator('#deploy').click();
  await page.getByText('Registry deployed. Save this address to check the same records on other devices.',{exact:true}).waitFor({timeout:30000});
  await page.locator('#verify').click();await page.getByText('This fingerprint is not registered in this registry',{exact:true}).waitFor();
  await page.locator('#register').click();await page.getByText('Fingerprint registered. The on-chain record is confirmed.',{exact:true}).waitFor({timeout:30000});
  assert.equal(await page.locator('#register').isDisabled(),true);
  assert.match(await page.locator('#registrant').textContent(),/^0x[\da-fA-F]{40}$/);
  const firstHash=await page.locator('#fingerprint').inputValue();
  await page.locator('#file').setInputFiles({name:'renamed.pdf',mimeType:'application/pdf',buffer:Buffer.from('abc')});
  await page.getByText('Fingerprint computed. File contents and filename were not uploaded.',{exact:true}).waitFor();
  assert.equal(await page.locator('#fingerprint').inputValue(),firstHash);
  await page.locator('#verify').click();await page.getByText('Registered · Fingerprint matches',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'mobile-preview.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'desktop-preview.png',fullPage:true});
  await page.locator('#file').setInputFiles({name:'proof.txt',mimeType:'text/plain',buffer:Buffer.from('abd')});
  await page.getByText('Fingerprint computed. File contents and filename were not uploaded.',{exact:true}).waitFor();
  await page.locator('#verify').click();await page.getByText('This fingerprint is not registered in this registry',{exact:true}).waitFor();
  await page.locator('#fingerprint').fill('bad');assert.equal(await page.locator('#verify').isDisabled(),true);
  await page.evaluate(()=>window.walletListeners.accountsChanged([]));assert.equal(await page.locator('#register').isDisabled(),true);
  const plain=await browser.newPage();await plain.goto('http://127.0.0.1:4174');await plain.locator('#connect').click();
  await plain.getByText('Open this site in MetaMask’s mobile browser, or use a desktop wallet extension.',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);console.log('PASS: mobile hashing, deployment, registration, duplicate prevention, verification, renamed and changed files, account change, invalid digest, no-wallet guidance, and desktop layout.');
}finally{await browser?.close();await rpc.disconnect();await new Promise(resolve=>server.httpServer.close(resolve));}
